package deploy

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"

	vyzorixspec "github.com/VinnsEdesigner/vyzorix-spec"
)

// ManifestTarget is the device and org a manifest targets.
type ManifestTarget struct {
	DeviceID string
	Org      string
	Name     string
}

// RenderManifest writes a vyzorix.toml from the recipe and the artifacts the
// builder produced. Every digest comes from the build, never a hand-typed value.
// Artifacts that share `app` become one [[app]] block, in first-appearance order;
// the app-level fields come from the first artifact of the group that sets them.
func RenderManifest(recipe *vyzorixspec.BuildRecipe, artifacts []BuiltArtifact, target ManifestTarget) ([]byte, error) {
	byName := indexArtifacts(artifacts)

	var buf bytes.Buffer

	buf.WriteString("# Generated by `vyzorix build`. Do not edit by hand.\n")
	buf.WriteString("# Every digest comes from the build; re-run the build to change an artifact.\n\n")
	buf.WriteString("[device]\n")
	fmt.Fprintf(&buf, "id  = %s\n", tomlString(target.DeviceID))
	fmt.Fprintf(&buf, "org = %s\n", tomlString(target.Org))

	if target.Name != "" {
		fmt.Fprintf(&buf, "name = %s\n", tomlString(target.Name))
	}

	for _, group := range groupByApp(recipe.Artifact) {
		if err := writeApp(&buf, group, byName); err != nil {
			return nil, err
		}
	}

	return buf.Bytes(), nil
}

// writeApp writes one [[app]] block and its artifacts.
func writeApp(buf *bytes.Buffer, group []vyzorixspec.BuildArtifact, byName map[string]BuiltArtifact) error {
	head := group[0]

	cmd := firstNonEmpty(group, func(a vyzorixspec.BuildArtifact) string { return a.Cmd })
	if cmd == "" {
		return fmt.Errorf("app %q has no cmd: name the entrypoint on at least one of its artifacts", head.App)
	}

	buf.WriteString("\n[[app]]\n")
	fmt.Fprintf(buf, "name = %s\n", tomlString(head.App))
	fmt.Fprintf(buf, "cmd  = %s\n", tomlString(cmd))

	// Bare keys must precede the first [[app.artifact]] (a TOML rule, not a
	// style choice). Only emit what the recipe set, so defaults stay the server's.
	if port := firstInt(group, func(a vyzorixspec.BuildArtifact) int { return a.Port }); port != 0 {
		fmt.Fprintf(buf, "port = %d\n", port)
	}

	if expose := firstNonEmpty(group, func(a vyzorixspec.BuildArtifact) string { return a.Expose }); expose != "" {
		fmt.Fprintf(buf, "expose = %s\n", tomlString(expose))
	}

	if autostart := firstBoolValue(group, func(a vyzorixspec.BuildArtifact) bool { return a.Autostart }); autostart {
		buf.WriteString("autostart = true\n")
	}

	if purge := firstBoolValue(group, func(a vyzorixspec.BuildArtifact) bool { return a.Purge }); purge {
		buf.WriteString("purge = true\n")
	}

	// pwa is a bare app key, so it must precede the [app.env] subtable: once a
	// table header opens, a later bare key would be parsed as a member of it.
	if pwa := firstBoolValue(group, func(a vyzorixspec.BuildArtifact) bool { return a.Pwa }); pwa {
		buf.WriteString("pwa = true\n")
	}

	if env := firstEnv(group); len(env) > 0 {
		buf.WriteString("\n[app.env]\n")
		for _, k := range sortedKeys(env) {
			fmt.Fprintf(buf, "%s = %s\n", k, tomlString(env[k]))
		}
	}

	for _, art := range group {
		built, ok := byName[art.Name]
		if !ok {
			return fmt.Errorf("the builder produced no artifact named %q for app %q", art.Name, art.App)
		}

		buf.WriteString("\n[[app.artifact]]\n")
		fmt.Fprintf(buf, "name   = %s\n", tomlString(art.Name))

		if built.Arch != "" && built.Arch != "all" {
			fmt.Fprintf(buf, "arch   = %s\n", tomlString(built.Arch))
		}

		fmt.Fprintf(buf, "url    = %s\n", tomlString(built.URL))
		fmt.Fprintf(buf, "sha256 = %s\n", tomlString(built.SHA256))

		if art.Kind != "" {
			fmt.Fprintf(buf, "kind   = %s\n", tomlString(art.Kind))
		}

		if built.Size > 0 {
			fmt.Fprintf(buf, "size   = %d\n", built.Size)
		}
	}

	return nil
}

// groupByApp groups artifacts by their app, preserving first-appearance order.
func groupByApp(arts []vyzorixspec.BuildArtifact) [][]vyzorixspec.BuildArtifact {
	var order []string
	groups := make(map[string][]vyzorixspec.BuildArtifact)

	for _, a := range arts {
		if _, seen := groups[a.App]; !seen {
			order = append(order, a.App)
		}

		groups[a.App] = append(groups[a.App], a)
	}

	out := make([][]vyzorixspec.BuildArtifact, 0, len(order))
	for _, app := range order {
		out = append(out, groups[app])
	}

	return out
}

// indexArtifacts keys the built artifacts by name.
func indexArtifacts(artifacts []BuiltArtifact) map[string]BuiltArtifact {
	byName := make(map[string]BuiltArtifact, len(artifacts))
	for _, a := range artifacts {
		byName[a.Name] = a
	}

	return byName
}

// tomlString quotes a value as a TOML basic string (a JSON string is a safe
// subset, so a stray quote in an env value cannot break the file).
func tomlString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return `""`
	}

	return string(b)
}

// firstNonEmpty returns the first artifact's non-empty value of pick.
func firstNonEmpty(arts []vyzorixspec.BuildArtifact, pick func(vyzorixspec.BuildArtifact) string) string {
	for _, a := range arts {
		if v := pick(a); v != "" {
			return v
		}
	}

	return ""
}

// firstInt returns the first artifact's non-zero value of pick.
func firstInt(arts []vyzorixspec.BuildArtifact, pick func(vyzorixspec.BuildArtifact) int) int {
	for _, a := range arts {
		if v := pick(a); v != 0 {
			return v
		}
	}

	return 0
}

// firstBoolValue returns the first artifact whose pick is true.
func firstBoolValue(arts []vyzorixspec.BuildArtifact, pick func(vyzorixspec.BuildArtifact) bool) bool {
	for _, a := range arts {
		if pick(a) {
			return true
		}
	}

	return false
}

// firstEnv returns the first artifact's non-empty env table.
func firstEnv(arts []vyzorixspec.BuildArtifact) map[string]string {
	for _, a := range arts {
		if len(a.Env) > 0 {
			return a.Env
		}
	}

	return nil
}

// sortedKeys returns a map's keys in sorted order, so the rendered manifest is
// byte-identical for the same recipe.
func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}

	sort.Strings(keys)

	return keys
}
